"""
Unified State and Data Contracts for Multi-Agent Research RAG System.
Combines:
  1. LangGraph StateGraph Reducer compatibility (TypedDict + operator.add).
  2. Research-assist strict contracts (SourceUnits, Claims, Evidence Gaps, Verification Guards).
  3. PaperQA2 Context Hashing & Citation Provenance IDs.
  4. Stanford STORM Multi-Perspective Inquiry attributes.
"""

from __future__ import annotations

import hashlib
import operator
from dataclasses import asdict, dataclass, field
from typing import Annotated, Any, Literal, Optional, TypedDict


def compute_context_hash(text: str, doc_id: str = "", page_no: int = 0) -> str:
    """Computes a SHA-256 fingerprint for a chunk/quote to guarantee citation provenance."""
    raw = f"{doc_id}:{page_no}:{text.strip()}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


@dataclass
class SourceUnit:
    """Verbatim text unit extracted directly from a source document."""
    id: str
    text: str
    doc_id: str = "unknown"
    page_no: int = 1
    bbox: Optional[list[float]] = None
    character_offset: int = 0
    context_hash: str = ""

    def __post_init__(self):
        if not self.context_hash:
            self.context_hash = compute_context_hash(self.text, self.doc_id, self.page_no)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class EvidenceSpan:
    """A verified quotation extracted by the Reader/Summarizer with offset tracking."""
    id: str
    quote: str
    source_unit_id: str
    doc_id: str
    page_no: int
    context_hash: str = ""
    relevance_score: float = 1.0

    def __post_init__(self):
        if not self.context_hash:
            self.context_hash = compute_context_hash(self.quote, self.doc_id, self.page_no)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class AtomicClaim:
    """An atomic, independently verifiable proposition generated by the Summarizer."""
    id: str
    text: str
    evidence_ids: list[str] = field(default_factory=list)
    confidence: float = 1.0

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class ClaimCheckResult:
    """Fact-checker decision on an atomic claim."""
    claim_id: str
    claim_text: str
    status: Literal["SUPPORT", "CONTRADICT", "INSUFFICIENT"]
    reason: str
    numerical_passed: bool = True
    dates_passed: bool = True
    confidence_score: float = 1.0
    contradicting_evidence: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class EvidenceGap:
    """An information void identified by Fact-Checker or Summarizer requiring iterative retrieval."""
    missing_aspect: str
    suggested_query: str
    perspective: str = "general"

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class AgentState(TypedDict, total=False):
    """
    Unified LangGraph StateGraph state passed across all 5 Agent nodes.
    Supports incremental list appending via Annotated[..., operator.add].
    """
    # 1. User & Request Context
    query: str
    intent: str
    pdf_path: Optional[str]
    perspectives: list[str]  # Multi-perspective angles (STORM-inspired)

    # 2. Retrieval Stage
    sub_queries: list[str]
    retrieved_docs: list[dict[str, Any]]
    seen_chunks: list[dict[str, Any]]  # Cumulative record across retries
    retrieval_strategy: str  # "bm25" | "dense" | "hybrid_rrf" | "remote_kaggle"

    # 3. Document Reading Stage
    document_schema: dict[str, Any]  # DocLayNet layout parse (tables, headers, text)
    source_units: list[dict[str, Any]]  # Exact offset source units

    # 4. Summarization Stage
    answer: str
    evidence_spans: list[dict[str, Any]]  # Verbatim quotes with hashes
    claims: list[dict[str, Any]]  # Atomic claims

    # 5. Fact-Checking Stage
    verified_claims: list[dict[str, Any]]  # Claims with SUPPORT status
    rejected_claims: list[dict[str, Any]]  # Claims with CONTRADICT / INSUFFICIENT
    evidence_gaps: list[dict[str, Any]]  # Missing aspects requiring re-retrieval
    fact_check_label: Literal["support", "contradict", "not_enough_info"]

    # 6. Report Generation Stage
    final_report: str
    written_report_data: dict[str, Any]

    # 7. Orchestration & Budget Controls
    retry_count: int  # Outer retry count (capped at MAX_ORCHESTRATOR_RETRY)
    factcheck_calls: int  # Total fact-check evaluations across whole task
    confidence: Literal["high", "low"]
    reasoning_trace: Annotated[list[dict[str, Any]], operator.add]
